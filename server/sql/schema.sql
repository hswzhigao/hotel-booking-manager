-- 酒店预订管理系统 表结构（幂等）
CREATE TABLE IF NOT EXISTS users (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  username VARCHAR(50) NOT NULL UNIQUE,
  password_hash VARCHAR(100) NOT NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS hotels (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  name VARCHAR(100) NOT NULL,
  city VARCHAR(50) DEFAULT NULL,
  address VARCHAR(255) DEFAULT NULL,
  phone VARCHAR(50) DEFAULT NULL,
  notes VARCHAR(500) DEFAULT NULL,
  checkin_presence TINYINT(1) DEFAULT NULL,
  checkin_info_required VARCHAR(1000) DEFAULT NULL,
  checkin_process VARCHAR(1000) DEFAULT NULL,
  official_phone VARCHAR(50) DEFAULT NULL,
  guide_text TEXT,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS room_types (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  hotel_id INT UNSIGNED NOT NULL,
  name VARCHAR(100) NOT NULL,
  bed_type VARCHAR(50) DEFAULT NULL,
  default_price DECIMAL(10,2) DEFAULT NULL,
  notes VARCHAR(500) DEFAULT NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE KEY uk_hotel_room (hotel_id, name),
  CONSTRAINT fk_rt_hotel FOREIGN KEY (hotel_id) REFERENCES hotels(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS benefit_holders (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  name VARCHAR(50) NOT NULL,
  wechat VARCHAR(100) DEFAULT NULL,
  phone VARCHAR(30) DEFAULT NULL,
  benefit_types VARCHAR(500) DEFAULT NULL,
  card_type VARCHAR(100) DEFAULT NULL,
  willing_present TINYINT(1) NOT NULL DEFAULT 0,
  willing_assist TINYINT(1) NOT NULL DEFAULT 0,
  active TINYINT(1) NOT NULL DEFAULT 1,
  hotel_benefit_count INT NOT NULL DEFAULT 0,
  golf_benefit_count INT NOT NULL DEFAULT 0,
  hotel_refresh_month TINYINT DEFAULT NULL,
  golf_refresh_month TINYINT DEFAULT NULL,
  availability ENUM('any','weekend_only','weekday_only') NOT NULL DEFAULT 'any',
  notes VARCHAR(500) DEFAULT NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS customers (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  name VARCHAR(50) NOT NULL,
  wechat VARCHAR(100) DEFAULT NULL,
  phone VARCHAR(30) DEFAULT NULL,
  is_hotel TINYINT(1) NOT NULL DEFAULT 1,
  is_golf TINYINT(1) NOT NULL DEFAULT 0,
  notes VARCHAR(500) DEFAULT NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS bookings (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  customer_id INT UNSIGNED NOT NULL,
  hotel_id INT UNSIGNED NOT NULL,
  check_in DATE NOT NULL,
  check_out DATE NOT NULL,
  nights INT UNSIGNED NOT NULL,
  sale_total DECIMAL(10,2) NOT NULL,
  cost_total DECIMAL(10,2) NOT NULL DEFAULT 0,
  order_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  benefit_used TINYINT(1) NOT NULL DEFAULT 0,
  status ENUM('active','completed','cancelled') NOT NULL DEFAULT 'active',
  notes VARCHAR(500) DEFAULT NULL,
  benefit_holder_id INT UNSIGNED DEFAULT NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  CONSTRAINT fk_bk_customer FOREIGN KEY (customer_id) REFERENCES customers(id),
  CONSTRAINT fk_bk_hotel FOREIGN KEY (hotel_id) REFERENCES hotels(id),
  CONSTRAINT fk_bk_holder FOREIGN KEY (benefit_holder_id) REFERENCES benefit_holders(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS booking_items (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  booking_id INT UNSIGNED NOT NULL,
  room_type_id INT UNSIGNED NOT NULL,
  price DECIMAL(10,2) NOT NULL,
  CONSTRAINT fk_bi_booking FOREIGN KEY (booking_id) REFERENCES bookings(id) ON DELETE CASCADE,
  CONSTRAINT fk_bi_room FOREIGN KEY (room_type_id) REFERENCES room_types(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS golf_orders (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  customer_id INT UNSIGNED NOT NULL,
  benefit_holder_id INT UNSIGNED DEFAULT NULL,
  course_name VARCHAR(100) NOT NULL,
  play_date DATE NOT NULL,
  tee_time VARCHAR(20) DEFAULT NULL,
  players TINYINT UNSIGNED NOT NULL DEFAULT 1,
  status ENUM('pending','booked','completed','cancelled') NOT NULL DEFAULT 'pending',
  teach_needed TINYINT(1) NOT NULL DEFAULT 0,
  sale_price DECIMAL(10,2) NOT NULL DEFAULT 0,
  cost_price DECIMAL(10,2) NOT NULL DEFAULT 0,
  channel VARCHAR(20) NOT NULL DEFAULT 'xianyu',
  benefit_used TINYINT(1) NOT NULL DEFAULT 1,
  order_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  notes VARCHAR(500) DEFAULT NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  CONSTRAINT fk_go_customer FOREIGN KEY (customer_id) REFERENCES customers(id),
  CONSTRAINT fk_go_holder FOREIGN KEY (benefit_holder_id) REFERENCES benefit_holders(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
